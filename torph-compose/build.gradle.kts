plugins {
    alias(libs.plugins.kotlin.multiplatform)
    alias(libs.plugins.android.kotlin.multiplatform.library)
    alias(libs.plugins.compose.compiler)
    alias(libs.plugins.androidx.baselineprofile)
    `maven-publish`
}

group = property("GROUP") as String
version = property("VERSION_NAME") as String

val hostOs = System.getProperty("os.name").lowercase()
val hostArch = System.getProperty("os.arch").lowercase()
val desktopCurrentOsArtifact = buildString {
    append("org.jetbrains.compose.desktop:desktop-jvm-")
    append(
        when {
            hostOs.contains("mac") || hostOs.contains("darwin") -> "macos"
            hostOs.contains("win") -> "windows"
            else -> "linux"
        },
    )
    append("-")
    append(if (hostArch == "aarch64" || hostArch == "arm64") "arm64" else "x64")
    append(":${libs.versions.composeMultiplatform.get()}")
}

kotlin {
    jvmToolchain(17)
    explicitApi()

    android {
        namespace = "des.c5inco.torph.compose"
        compileSdk { version = release(37) { minorApiLevel = 1 } }
        minSdk = libs.versions.minSdk.get().toInt()
        // Compiled against 37.1 like the apps that use it, but no 37.1 API is used, so apps need only 37
        // (the floor Compose 1.12 sets). Left alone, AGP would require the minor version too.
        aarMetadata.minCompileSdk = 37

        withHostTestBuilder {}
        withDeviceTestBuilder {
            sourceSetTreeName = "test"
        }.configure {
            instrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        }
    }

    jvm("desktop")

    sourceSets {
        commonMain.dependencies {
            api(project(":torph-core"))
            implementation(libs.jetbrains.compose.foundation)
            implementation(libs.jetbrains.compose.animation)
            implementation(libs.jetbrains.compose.ui)
            implementation(libs.jetbrains.compose.ui.text)
            implementation(libs.kotlinx.coroutines.core)
        }
        named("desktopMain") {
            dependencies {
                implementation(libs.icu4j)
            }
        }
        commonTest.dependencies {
            implementation(libs.kotlin.test)
            implementation(libs.junit)
        }
        named("desktopTest") {
            dependencies {
                implementation(desktopCurrentOsArtifact)
                implementation(libs.jetbrains.compose.ui.test.junit4)
            }
        }
        named("androidDeviceTest") {
            dependencies {
                implementation(project.dependencies.platform(libs.compose.bom))
                implementation(libs.androidx.junit)
                // Pin androidx.test above what ui-test-junit4 pulls in (espresso 3.5.0 / runner 1.5.0),
                // which crashes on Android 17 (InputManager.getInstance was removed).
                implementation(libs.androidx.espresso.core)
                implementation(libs.androidx.test.runner)
                implementation(libs.androidx.test.core)
                implementation(libs.androidx.test.monitor)
                implementation(libs.compose.ui.test.junit4)
                implementation(libs.compose.ui.test.manifest)
            }
        }
    }
}

